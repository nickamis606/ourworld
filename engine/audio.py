"""Audio: looping chiptune music per place + short SFX.

Never crashes: if the mixer can't open (headless, no sound card, missing files,
OURWORLD_NOSOUND=1) every call becomes a no-op. Files are generated by
tools/make_audio.py into assets/audio/.
"""
import os

import pygame

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
AUDIO_DIR = os.path.join(ROOT, "assets", "audio")

# place -> music track
PLACE_MUSIC = {
    "home": "home", "backyard": "town", "park": "town", "sweeties_candy_shop": "shop",
    "gens_garden": "shop", "arcade": "arcade", "pond": "town", "library": "calm", "spa": "calm",
    "willow_woods": "woods", "town_square": "town", "lantern_hill": "calm",
}
INDOOR = {"home", "sweeties_candy_shop", "gens_garden", "arcade", "library", "spa"}


def track_for(place, period="day", season="fall", festival=False):
    if festival and place in ("town_square", "lantern_hill"):
        return "festival"
    if period == "night" and place not in INDOOR:
        return "night"
    if season == "winter" and place not in INDOOR and place != "willow_woods":
        return "winter"
    return PLACE_MUSIC.get(place, "home")


class Audio:
    def __init__(self):
        self.enabled = False
        self.music_vol = 0.6
        self.sfx_vol = 0.8
        self.muted = False
        self.current = None
        self.played = []            # recent sfx names (tests/debug)
        self._sfx = {}
        if os.environ.get("OURWORLD_NOSOUND") == "1":
            return
        try:
            if not pygame.mixer.get_init():
                pygame.mixer.pre_init(22050, -16, 1, 512)
                pygame.mixer.init()
            pygame.mixer.set_num_channels(8)
            self.enabled = os.path.isdir(AUDIO_DIR)
        except (pygame.error, NotImplementedError, AttributeError, OSError):
            self.enabled = False

    # ------------------------------------------------------------ settings
    def apply(self, music_vol, sfx_vol, muted):
        self.music_vol = max(0.0, min(1.0, music_vol))
        self.sfx_vol = max(0.0, min(1.0, sfx_vol))
        self.muted = bool(muted)
        if self.enabled:
            try:
                pygame.mixer.music.set_volume(0.0 if self.muted else self.music_vol)
            except pygame.error:
                pass

    # --------------------------------------------------------------- music
    def music(self, track):
        if track == self.current:
            return
        self.current = track
        if not self.enabled:
            return
        path = os.path.join(AUDIO_DIR, f"music_{track}.wav")
        try:
            if not os.path.exists(path):
                pygame.mixer.music.stop()
                return
            pygame.mixer.music.load(path)
            pygame.mixer.music.set_volume(0.0 if self.muted else self.music_vol)
            pygame.mixer.music.play(-1, fade_ms=400)
        except pygame.error:
            pass

    def stop_music(self):
        self.current = None
        if self.enabled:
            try:
                pygame.mixer.music.fadeout(300)
            except pygame.error:
                pass

    # ----------------------------------------------------------------- sfx
    def sfx(self, name):
        self.played.append(name)
        if len(self.played) > 32:
            del self.played[:16]
        if not self.enabled or self.muted or self.sfx_vol <= 0:
            return
        snd = self._sfx.get(name)
        if snd is None:
            path = os.path.join(AUDIO_DIR, f"sfx_{name}.wav")
            try:
                snd = pygame.mixer.Sound(path) if os.path.exists(path) else False
            except pygame.error:
                snd = False
            self._sfx[name] = snd
        if snd:
            try:
                snd.set_volume(self.sfx_vol)
                snd.play()
            except pygame.error:
                pass

    def shutdown(self):
        if self.enabled:
            try:
                pygame.mixer.music.stop()
                pygame.mixer.quit()
            except pygame.error:
                pass
        self.enabled = False
